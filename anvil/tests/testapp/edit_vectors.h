// The golden vectors for the edit recipe (docs/21-image-edits.md §2.2).
//
// The recipe is a byte-exact contract between two codecs in two languages —
// anvil/images/recipe.h here and hammer's `src/edit/recipe.ts` there — and a
// codec written against its own vectors is two copies of one belief. These
// were produced by a third implementation, a throwaway script written from the
// layout in the document rather than from either codec, and both suites assert
// against them. `testapp_emit_edit_vectors` prints them as the JSON fixture
// hammer commits.
//
// Every vector is decoded and planned against a master of `source_width` ×
// `source_height` under kEditVectorLimits. `fault` is empty for a vector that
// must succeed, and `out_width` × `out_height` is then the size it renders at.

