// One label per declared locale, in the locale table's order (§5). A shorter
// array is an index out of range the moment a staff editor switches language,
// which is the defect nobody sees in the locale they develop in.
function checkLabels(
    collector: Collector,
    labels: readonly string[],
    locales: number,
    key: string,
): void {
    if (labels.length !== locales) {
        collector.error(key, "out-of-range");
    }
    for (let i = 0; i < labels.length; i += 1) {
        const label = labels[i];
        if (label !== undefined && kNotPlainText.test(label)) {
            collector.error(`${key}[${i}]`, "not-plain-text");
        }
    }
}

function checkFieldTypes(collector: Collector, types: readonly FieldTypeSpec[]): void {
    const seen = newSeen();
    const answers = new Set<string>();
    for (let i = 0; i < types.length; i += 1) {
        const type = types[i];
        if (type === undefined) {
            continue;
        }
        const key = `tables.field_types[${i}]`;
        checkName(collector, seen, type.name, `${key}.name`);
        checkValue(collector, seen, type.code, `${key}.code`);

        // The answer kind is anvil's vocabulary and is emitted as a union of
        // what the table holds, so the only question here is whether it can
        // reach the file.
        if (type.answer !== null && !answers.has(type.answer)) {
            collector.name(type.answer, `${key}.answer`);
            answers.add(type.answer);
        }

        // A PII type produces no answer at all. The two say the same thing and
        // a client branches on both, so a descriptor where they disagree is one
        // whose renderer would draw a control for a value it can never read.
        if (type.pii === (type.answer !== null)) {
            collector.error(`${key}.answer`, "unknown-member");
        }

        if (type.default_code_points < 0) {
            collector.error(`${key}.default_code_points`, "out-of-range");
        }
    }
}

function checkSections(collector: Collector, sections: readonly SectionSpec[], locales: number): void {
    const seen = newSeen();
    for (let i = 0; i < sections.length; i += 1) {
        const section = sections[i];
        if (section === undefined) {
            continue;
        }
        const key = `tables.sections[${i}]`;
        checkName(collector, seen, section.key, `${key}.key`);

        const identifier = sectionIdentifier(section.key);
        if (seen.identifiers.has(identifier)) {
            collector.error(`${key}.key`, "identifier-collision");
        } else {
            seen.identifiers.add(identifier);
        }

        // The page a preview has to land a reader on, and a value the client
        // navigates to. It is checked as a route pattern for the same reason a
        // route's path is: `//evil.example` is a host, not a path.
        if (!section.site_path.startsWith("/")) {
            collector.error(`${key}.site_path`, "path-not-absolute");
        } else if (!kRoutePattern.test(section.site_path)) {
            collector.error(`${key}.site_path`, "path-not-a-route-pattern");
        }

        const fieldKeys = new Set<string>();
        for (let f = 0; f < section.fields.length; f += 1) {
            const field = section.fields[f];
            if (field === undefined) {
                continue;
            }
            const at = `${key}.fields[${f}]`;
            if (field.key.length === 0) {
                collector.error(`${at}.key`, "empty");
            } else if (!kFieldName.test(field.key)) {
                collector.error(`${at}.key`, "not-spellable");
            } else if (fieldKeys.has(field.key)) {
                collector.error(`${at}.key`, "duplicate-name");
            } else {
                fieldKeys.add(field.key);
            }

            collector.name(field.type, `${at}.type`);
            checkLabels(collector, field.labels, locales, `${at}.labels`);

            if (field.max_code_points < 0) {
                collector.error(`${at}.max_code_points`, "out-of-range");
            }

            const choices = new Set<string>();
            for (let c = 0; c < field.choices.length; c += 1) {
                const choice = field.choices[c];
                if (choice === undefined) {
                    continue;
                }
                // A choice is a STORED value rather than a name this generator
                // spells, so it is held to what a string reaching the file must
                // be and to nothing narrower: an application whose options are
                // written in its own script is not a malformed application.
                if (choice.length === 0) {
                    collector.error(`${at}.choices[${c}]`, "empty");
                } else if (kNotPlainText.test(choice)) {
                    collector.error(`${at}.choices[${c}]`, "not-plain-text");
                } else if (choices.has(choice)) {
                    collector.error(`${at}.choices[${c}]`, "duplicate-name");
                } else {
                    choices.add(choice);
                }
            }
        }

        const slots = new Set<string>();
        for (let m = 0; m < section.images.length; m += 1) {
            const image = section.images[m];
            if (image === undefined) {
                continue;
            }
            const at = `${key}.images[${m}]`;
            collector.name(image.slot, `${at}.slot`);
            if (slots.has(image.slot)) {
                collector.error(`${at}.slot`, "duplicate-name");
            } else {
                slots.add(image.slot);
            }
            checkLabels(collector, image.labels, locales, `${at}.labels`);
            if (image.min_width < 0 || image.min_height < 0) {
                collector.error(at, "out-of-range");
            }
            if (image.aspect !== null && (image.aspect.num <= 0 || image.aspect.den <= 0)) {
                collector.error(`${at}.aspect`, "not-positive");
            }
        }
    }
}

function checkTopics(
    collector: Collector,
    topics: readonly TopicSpec[],
    permissions: ReadonlySet<string>,
): void {
    const seen = newSeen();
    const words = new Set<string>();
    for (let i = 0; i < topics.length; i += 1) {
        const topic = topics[i];
        if (topic === undefined) {
            continue;
        }
        const key = `tables.topics[${i}]`;
        checkName(collector, seen, topic.key, `${key}.key`);
        checkValue(collector, seen, topic.code, `${key}.code`);

        const identifier = topicIdentifier(topic.key);
        if (seen.identifiers.has(identifier)) {
            collector.error(`${key}.key`, "identifier-collision");
        } else {
            seen.identifiers.add(identifier);
        }

        // Checked once per distinct word rather than once per row: these are
        // anvil's vocabulary, so the table repeats a handful of them, and the
        // key a problem is reported against is still the field it is in.
        const word = (value: string, at: string): void => {
            if (words.has(value)) {
                return;
            }
            words.add(value);
            collector.name(value, at);
        };
        word(topic.fanout, `${key}.fanout`);
        word(topic.scope, `${key}.scope`);
        for (let c = 0; c < topic.default_channels.length; c += 1) {
            const channel = topic.default_channels[c];
            if (channel !== undefined) {
                word(channel, `${key}.default_channels[${c}]`);
            }
        }

        for (let p = 0; p < topic.perms.length; p += 1) {
            const perm = topic.perms[p];
            if (perm !== undefined && !permissions.has(perm)) {
                collector.error(`${key}.perms[${p}]`, "unknown-permission");
            }
        }

        // anvil DERIVES visibility from the permission set — a topic requiring
        // nothing is public and any other is a holder's — so a descriptor where
        // the two disagree is not anvil's output. It is refused rather than
        // reconciled, and in both directions: `public` with a permission is a key
        // emitted into a bundle that the permission was supposed to gate, which
        // is the failure §4.1 exists to stop, and `holder` with none withholds a
        // key nothing protects, which reads as a gate that is not there.
        const gated = topic.perms.length !== 0;
        if (gated !== (topic.visibility !== "public")) {
            collector.error(`${key}.visibility`, "visibility-contradicts-perms");
        }

        if (topic.coalesce_window_s < 0) {
            collector.error(`${key}.coalesce_window_s`, "out-of-range");
        }
        if (topic.retention_days <= 0) {
            collector.error(`${key}.retention_days`, "not-positive");
        }
    }
}

function checkEvents(collector: Collector, events: readonly EventSpec[]): void {
    const seen = newSeen();
    const classes = new Set<string>();
    for (let i = 0; i < events.length; i += 1) {
        const event = events[i];
        if (event === undefined) {
            continue;
        }
        const key = `tables.events[${i}]`;
        checkName(collector, seen, event.name, `${key}.name`);
        checkValue(collector, seen, event.code, `${key}.code`);

        const identifier = eventIdentifier(event.name);
        if (seen.identifiers.has(identifier)) {
            collector.error(`${key}.name`, "identifier-collision");
        } else {
            seen.identifiers.add(identifier);
        }

        if (!classes.has(event.class)) {
            collector.name(event.class, `${key}.class`);
            classes.add(event.class);
        }

        const names = new Set<string>();
        for (let d = 0; d < event.dimensions.length; d += 1) {
            const dimension = event.dimensions[d];
            if (dimension === undefined) {
                continue;
            }
            const at = `${key}.dimensions[${d}]`;
            collector.name(dimension.name, `${at}.name`);
            if (names.has(dimension.name)) {
                collector.error(`${at}.name`, "duplicate-name");
            } else {
                names.add(dimension.name);
            }

            // The row stores the INDEX into this set, so a duplicate is two
            // names for one stored number and a value outside it is a row the
            // ingest path drops.
            const values = new Set<string>();
            for (let v = 0; v < dimension.values.length; v += 1) {
                const value = dimension.values[v];
                if (value === undefined) {
                    continue;
                }
                if (value.length === 0) {
                    collector.error(`${at}.values[${v}]`, "empty");
                } else if (kNotPlainText.test(value)) {
                    collector.error(`${at}.values[${v}]`, "not-plain-text");
                } else if (values.has(value)) {
                    collector.error(`${at}.values[${v}]`, "duplicate-name");
                } else {
                    values.add(value);
                }
            }
        }
    }
}

function checkMedia(collector: Collector, media: MediaTable): void {
    collector.name(media.default_role, "tables.media.default_role");

    const namespaces = new Set<string>();
    for (let i = 0; i < media.namespaces.length; i += 1) {
        const namespace = media.namespaces[i];
        if (namespace === undefined) {
            continue;
        }
        const key = `tables.media.namespaces[${i}]`;
        collector.name(namespace.ns, `${key}.ns`);
        if (namespaces.has(namespace.ns)) {
            collector.error(`${key}.ns`, "duplicate-name");
        } else {
            namespaces.add(namespace.ns);
        }

        // A namespace that accepts nothing is a namespace nothing can be
        // uploaded to, which is an emitter that forgot rather than a policy: the
        // accept list exists so the client's check and the server's are one
        // list, and an empty one makes the client's refuse everything.
        if (namespace.accepts.length === 0) {
            collector.error(`${key}.accepts`, "empty");
        }
        const accepted = new Set<string>();
        for (let a = 0; a < namespace.accepts.length; a += 1) {
            const type = namespace.accepts[a];
            if (type === undefined) {
                continue;
            }
            const at = `${key}.accepts[${a}]`;
            // `type/subtype`, lowercase, with no parameters. It reaches an
            // `accept` attribute and a comparison against `File.type`, which is
            // the browser's lowercase essence string — so a value with a
            // parameter or a capital never matches the thing it is checked
            // against, and the upload is refused for a reason nobody can see.
            if (!kMediaType.test(type)) {
                collector.error(at, "not-a-media-type");
            }
            if (accepted.has(type)) {
                collector.error(at, "duplicate-name");
            } else {
                accepted.add(type);
            }
        }

        const roles = new Set<string>();
        for (let r = 0; r < namespace.roles.length; r += 1) {
            const role = namespace.roles[r];
            if (role === undefined) {
                continue;
            }
            const at = `${key}.roles[${r}]`;
            collector.name(role.role, `${at}.role`);
            if (roles.has(role.role)) {
                collector.error(`${at}.role`, "duplicate-name");
            } else {
                roles.add(role.role);
            }
            if (role.width <= 0) {
                collector.error(`${at}.width`, "not-positive");
            }
        }

        // The role a request with no role segment resolves to — so a namespace
        // that does not serve it is one where forgetting the segment is a 404
        // rather than a smaller image, and the caller finds out in production.
        if (!roles.has(media.default_role)) {
            collector.error(`${key}.roles`, "unknown-media-role");
        }
    }
}

function checkRoutes(collector: Collector, tables: Tables): void {
    const permissions = new Set(tables.permissions.map((permission) => permission.name));
    const scopes = new Set(tables.capability_scopes.map((scope) => scope.name));
    const buckets = new Set(tables.rate_limits.map((bucket) => bucket.bucket));

    const seen = newSeen();
    const requiredScopes = new Set<string>();
    const namedBuckets = new Set<string>();

    for (let i = 0; i < tables.routes.length; i += 1) {
        const route = tables.routes[i];
        if (route === undefined) {
            continue;
        }
        const key = `tables.routes[${i}]`;
        checkName(collector, seen, route.id, `${key}.id`);

        const identifier = routeIdentifier(route.id);
        if (seen.identifiers.has(identifier)) {
            collector.error(`${key}.id`, "identifier-collision");
        } else {
            seen.identifiers.add(identifier);
        }

        pathParameters(collector, route.path, `${key}.path`);

        // `ANY` is not a method. It is a declaration that every method shares
        // one policy, and anvil emits it so that a client fails loudly on a
        // description that forgot to name one rather than defaulting to GET and
        // silently calling the wrong thing (`descriptor/route_description.h`).
        //
        // For a PUBLIC route the method is emitted as a value, so `ANY` is a
        // client that cannot call a route it can see: a generation failure, which
        // is where a thing an application must supply belongs. For a holder route
        // the method is not emitted at all — it arrives with the session — so the
        // failure cannot happen until run time, and this is the only place the
        // build can say so.
        if (route.method === "ANY") {
            if (route.visibility === "public") {
                collector.error(`${key}.method`, "unusable-method");
            } else {
                collector.warn(`${key}.method`, "unusable-method");
            }
        }

        for (let p = 0; p < route.perms.length; p += 1) {
            const perm = route.perms[p];
            if (perm !== undefined && !permissions.has(perm)) {
                collector.error(`${key}.perms[${p}]`, "unknown-permission");
            }
        }

        if (route.capability.length !== 0) {
            if (scopes.has(route.capability)) {
                requiredScopes.add(route.capability);
            } else {
                collector.error(`${key}.capability`, "unknown-capability-scope");
            }
        }

        if (route.rate_limit.length !== 0) {
            if (buckets.has(route.rate_limit)) {
                namedBuckets.add(route.rate_limit);
            } else {
                collector.error(`${key}.rate_limit`, "unknown-rate-limit-bucket");
            }
        }

        if (route.response !== null) {
            // Two fields with one key is a body whose second value overwrites
            // the first in every JSON parser there is, and an emitted type with
            // a duplicate property does not compile — so it fails here, naming
            // the field, rather than in the consumer's build naming a line of
            // generated code.
            const fields = new Set<string>();
            for (let f = 0; f < route.response.fields.length; f += 1) {
                const field = route.response.fields[f];
                if (field === undefined) {
                    continue;
                }
                if (fields.has(field.name)) {
                    collector.error(`${key}.response.fields[${f}].name`, "duplicate-field");
                } else {
                    fields.add(field.name);
                }
            }
        }

        if (route.page !== null) {
            if (route.page.cursor.length === 0) {
                collector.error(`${key}.page.cursor`, "empty");
            } else if (!kFieldName.test(route.page.cursor)) {
                collector.error(`${key}.page.cursor`, "not-spellable");
            }
            if (route.page.limit_max <= 0) {
                collector.error(`${key}.page.limit_max`, "not-positive");
            } else if (route.page.limit_max > tables.limits.page_limit_max) {
                collector.error(`${key}.page.limit_max`, "above-maximum");
            }
        }
    }

    for (let i = 0; i < tables.capability_scopes.length; i += 1) {
        const scope = tables.capability_scopes[i];
        if (scope !== undefined && !requiredScopes.has(scope.name)) {
            collector.warn(`tables.capability_scopes[${i}].name`, "no-route-requires-it");
        }
    }

    for (let i = 0; i < tables.rate_limits.length; i += 1) {
        const bucket = tables.rate_limits[i];
        if (bucket !== undefined && !namedBuckets.has(bucket.bucket)) {
            collector.warn(`tables.rate_limits[${i}].bucket`, "no-route-names-it");
        }
    }
}

