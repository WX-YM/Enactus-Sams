// --- what a route answers with ----------------------------------------------
//
// anvil writes its success bodies through a response binder, so the shape is a
// declaration the server is checked against rather than a comment beside the
// handler: writing a key that is not next, writing one of the wrong type or
// stopping early are `static_assert`s there (`http/response_writer.h`). That is
// what makes this table worth reading — a schema nothing enforced would be a
// description of bytes nobody sends, and generating types from one is worse
// than generating none, because the lie type-checks.
//
// The grammar is deliberately small, and the smallness is the point:
// `kind_name()` in anvil names six types, each of which is a distinction a
// CLIENT has to make rather than a JSON type. `uuid` and `string` are both JSON
// strings and one of them is parsed into a typed id; `time` is a JSON string a
// client turns into an instant. A vocabulary that collapsed them would describe
// the bytes correctly and the types uselessly.
//
// It is NOT re-declared as a closed set beyond what the emission branches on,
// for the reason the header above gives: a copy of anvil's enum is the copy
// nobody updates. A type this generator does not know is an error against the
// field that carries it rather than a table-wide failure, so a descriptor that
// grew a seventh kind names the one route hammer cannot type yet.
export type ResponseFieldType = "string" | "int" | "bool" | "uuid" | "time" | "strings";

