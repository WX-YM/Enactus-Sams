const kSha256 = /^[0-9a-f]{64}$/;

export function readDescriptor(
    source: unknown,
): Result<DescriptorReading, readonly DescriptorProblem[]> {
    const collector = new Collector();

    const root = collector.object(source, "");
    if (root === null) {
        return fail(collector.errors);
    }

    const format = collector.integer(root, "descriptor", "descriptor");
    if (format !== null && format !== kSupportedFormat) {
        collector.error("descriptor", "unsupported-format");
    }

    const emittedBy = collector.string(root, "emitted_by", "emitted_by");
    const hash = collector.string(root, "hash", "hash");
    if (hash !== null && !kSha256.test(hash)) {
        collector.error("hash", "not-a-sha256");
    }

    const app = collector.object(root["app"], "app");
    const appName = app === null ? null : collector.string(app, "name", "app.name");
    const appVersion = app === null ? null : collector.string(app, "version", "app.version");

    const rawTables = collector.object(root["tables"], "tables");
    if (rawTables === null) {
        return fail(collector.errors);
    }

    const errorCodes = readErrorCodes(collector, rawTables["error_codes"]);
    const reasons = readEnumerators(collector, rawTables["validation_reasons"], "tables.validation_reasons");
    const permissions = readPermissions(collector, rawTables["permissions"]);
    const locales = readLocales(collector, rawTables["locales"]);
    const routes = readRoutes(collector, rawTables["routes"]);
    const scopes = readCapabilityScopes(collector, rawTables["capability_scopes"]);
    const rateLimits = readRateLimits(collector, rawTables["rate_limits"]);
    const limits = readLimits(collector, rawTables["limits"]);
    const fieldTypes = readFieldTypes(collector, rawTables["field_types"]);
    const sections = readSections(collector, rawTables["sections"]);
    const topics = readTopics(collector, rawTables["topics"]);
    const events = readEvents(collector, rawTables["events"]);
    const media = readMedia(collector, rawTables["media"]);

    if (
        format === null ||
        emittedBy === null ||
        hash === null ||
        appName === null ||
        appVersion === null ||
        errorCodes === null ||
        reasons === null ||
        permissions === null ||
        locales === null ||
        routes === null ||
        scopes === null ||
        rateLimits === null ||
        limits === null ||
        fieldTypes === null ||
        sections === null ||
        topics === null ||
        events === null ||
        media === null ||
        collector.errors.length !== 0
    ) {
        return fail(collector.errors);
    }

    const tables: Tables = {
        error_codes: errorCodes,
        validation_reasons: reasons,
        permissions,
        locales,
        routes,
        capability_scopes: scopes,
        rate_limits: rateLimits,
        limits,
        field_types: fieldTypes,
        sections,
        topics,
        events,
        media,
    };

    checkErrorCodes(collector, tables.error_codes);
    checkEnumerators(collector, tables.validation_reasons, "tables.validation_reasons");
    checkPermissions(collector, tables.permissions);
    checkLocales(collector, tables.locales);
    checkCapabilityScopes(collector, tables.capability_scopes);
    checkRateLimits(collector, tables.rate_limits);
    checkLimits(collector, tables.limits);
    checkRoutes(collector, tables);
    checkFieldTypes(collector, tables.field_types);
    checkSections(collector, tables.sections, tables.locales.length);
    checkTopics(
        collector,
        tables.topics,
        new Set(tables.permissions.map((permission) => permission.name)),
    );
    checkEvents(collector, tables.events);
    checkMedia(collector, tables.media);

    if (collector.errors.length !== 0) {
        return fail(collector.errors);
    }

    const descriptor: Descriptor = {
        descriptor: format,
        emitted_by: emittedBy,
        app: { name: appName, version: appVersion },
        hash,
        tables,
    };
    return ok({ descriptor, warnings: collector.warnings });
}

// JSON.parse throws, and a file that is not JSON is an expected condition rather
// than a programmer error: it is whatever was on disk.
export function readDescriptorJson(
    text: string,
): Result<DescriptorReading, readonly DescriptorProblem[]> {
    let parsed: unknown;
    try {
        parsed = JSON.parse(text);
    } catch {
        return fail([{ key: "", issue: "not-json" }]);
    }
    return readDescriptor(parsed);
}
