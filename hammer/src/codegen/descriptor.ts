// The descriptor, narrowed exactly once.
//
// Everything an application supplies arrives through this file (`ENGINEERING_RULES.md` §1),
// so every guarantee downstream of it rests on what is checked here. The checks
// are the ones anvil's own `well_formed()` makes — a duplicate bit, a duplicate
// name, an empty name, a bit out of range, a route naming a permission, a scope
// or a bucket that does not exist — made again on this side of the wire.
//
// Made again rather than trusted, because a descriptor is a FILE. It is copied
// between repositories, hand-edited by somebody in a hurry, and regenerated by a
// build that may be older than the server it claims to describe. A malformed one
// fails generation naming the key; the alternative is a generated module that
// compiles and lies, and the lie is an authority check reading the wrong bit.
//
// --- what is an error and what is a warning ---------------------------------
//
// A route naming a capability scope that does not exist is an error: the emitted
// type would require a `Capability<Scope>` of a scope with no minting call, and
// nothing would compile. The reverse — a scope no route requires, a bucket no
// route names — is a WARNING, and the reference descriptor is why. anvil limits
// by keys that are not route buckets and mints scopes for operations whose
// routes its emitter does not carry, so a hard failure there rejects anvil's own
// output. A dead entry still reads as coverage, so it is reported rather than
// dropped.
//
// The field-type and section checks (`docs/01-seams.md` §§7–8) are absent because
// the tables are: anvil records them as open rather than guessing at a shape, and
// a check against a table nobody emits is a check nothing can fail.

