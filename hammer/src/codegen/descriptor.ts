const kAccess: readonly RouteAccess[] = ["public", "authenticated", "guarded", "stealth"];
const kVisibility: readonly RouteVisibility[] = ["public", "holder"];
const kMethods: readonly RouteMethod[] = ["GET", "HEAD", "POST", "PUT", "PATCH", "DELETE", "ANY"];
const kResponseKinds: readonly ResponseKind[] = ["object", "array"];
const kResponseFieldTypes: readonly ResponseFieldType[] = [
    "string",
    "int",
    "bool",
    "uuid",
    "time",
    "strings",
];

function readPage(collector: Collector, raw: unknown, at: string): PageSpec | null | undefined {
    if (raw === null || raw === undefined) {
        return null;
    }
    const page = collector.object(raw, at);
    if (page === null) {
        return undefined;
    }
    const cursor = collector.string(page, "cursor", `${at}.cursor`);
    const limitMax = collector.integer(page, "limit_max", `${at}.limit_max`);
    if (cursor === null || limitMax === null) {
        return undefined;
    }
    return { cursor, limit_max: limitMax };
}

// `undefined` is the sentinel for "malformed", the way `readPage` uses it, so
// that a route with a broken schema fails generation rather than silently
// becoming an untyped one. A null response is a route anvil declared none for,
// which is not a defect.
function readResponse(
    collector: Collector,
    raw: unknown,
    at: string,
): ResponseSpec | null | undefined {
    if (raw === null || raw === undefined) {
        return null;
    }
    const response = collector.object(raw, at);
    if (response === null) {
        return undefined;
    }
    const kind = collector.member(response, "kind", `${at}.kind`, kResponseKinds);
    const rawFields = collector.array(response["fields"], `${at}.fields`);
    if (kind === null || rawFields === null) {
        return undefined;
    }

    const fields: ResponseFieldSpec[] = [];
    for (let i = 0; i < rawFields.length; i += 1) {
        const key = `${at}.fields[${i}]`;
        const entry = collector.object(rawFields[i], key);
        if (entry === null) {
            continue;
        }
        const name = collector.string(entry, "name", `${key}.name`);
        const type = collector.member(entry, "type", `${key}.type`, kResponseFieldTypes);
        const nullable = collector.boolean(entry, "nullable", `${key}.nullable`);
        if (name === null || type === null || nullable === null) {
            continue;
        }
        // A key that is not a key. It is emitted as a quoted property name so
        // any text would compile, but a body key is also what a call site reads
        // by hand, and an empty one is a field nothing can name.
        if (name.length === 0) {
            collector.error(`${key}.name`, "empty");
            continue;
        }
        fields.push({ name, type, nullable });
    }

    // A declared response with no field is not an object shape; it is a
    // declaration somebody started and did not finish. anvil emits `null` for
    // "no declaration", so this cannot be that.
    if (fields.length === 0) {
        collector.error(`${at}.fields`, "empty");
        return undefined;
    }
    if (fields.length !== rawFields.length) {
        return undefined;
    }
    return { kind, fields };
}

function readRoutes(collector: Collector, raw: unknown): RouteSpec[] | null {
    const entries = collector.array(raw, "tables.routes");
    if (entries === null) {
        return null;
    }
    const out: RouteSpec[] = [];
    for (let i = 0; i < entries.length; i += 1) {
        const key = `tables.routes[${i}]`;
        const entry = collector.object(entries[i], key);
        if (entry === null) {
            continue;
        }
        const id = collector.string(entry, "id", `${key}.id`);
        const method = collector.member(entry, "method", `${key}.method`, kMethods);
        const path = collector.string(entry, "path", `${key}.path`);
        const access = collector.member(entry, "access", `${key}.access`, kAccess);
        const visibility = collector.member(entry, "visibility", `${key}.visibility`, kVisibility);
        const capability = collector.string(entry, "capability", `${key}.capability`);
        const rateLimit = collector.string(entry, "rate_limit", `${key}.rate_limit`);
        const idempotent = collector.boolean(entry, "idempotent", `${key}.idempotent`);
        const page = readPage(collector, entry["page"], `${key}.page`);
        const response = readResponse(collector, entry["response"], `${key}.response`);
        const rawPerms = collector.array(entry["perms"], `${key}.perms`);

        const perms: string[] = [];
        if (rawPerms !== null) {
            for (let p = 0; p < rawPerms.length; p += 1) {
                const perm = rawPerms[p];
                if (typeof perm !== "string") {
                    collector.error(`${key}.perms[${p}]`, "not-a-string");
                    continue;
                }
                perms.push(perm);
            }
        }

        if (
            id === null ||
            method === null ||
            path === null ||
            access === null ||
            visibility === null ||
            capability === null ||
            rateLimit === null ||
            idempotent === null ||
            page === undefined ||
            response === undefined ||
            rawPerms === null
        ) {
            continue;
        }

        out.push({
            id,
            method,
            path,
            access,
            visibility,
            perms,
            capability,
            rate_limit: rateLimit,
            idempotent,
            page,
            response,
        });
    }
    return out;
}

