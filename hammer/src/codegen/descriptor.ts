function readErrorCodes(collector: Collector, raw: unknown): ErrorCodeTable | null {
    const table = collector.object(raw, "tables.error_codes");
    if (table === null) {
        return null;
    }
    const max = collector.integer(table, "max", "tables.error_codes.max");
    const entries = collector.array(table["codes"], "tables.error_codes.codes");
    if (max === null || entries === null) {
        return null;
    }

    const codes: ErrorCodeSpec[] = [];
    for (let i = 0; i < entries.length; i += 1) {
        const key = `tables.error_codes.codes[${i}]`;
        const entry = collector.object(entries[i], key);
        if (entry === null) {
            continue;
        }
        const name = collector.string(entry, "name", `${key}.name`);
        const value = collector.integer(entry, "value", `${key}.value`);
        const http = collector.integer(entry, "http", `${key}.http`);
        const hidden = collector.boolean(entry, "stealth_hidden", `${key}.stealth_hidden`);
        if (name === null || value === null || http === null || hidden === null) {
            continue;
        }
        codes.push({ name, value, http, stealth_hidden: hidden });
    }
    return { max, codes };
}

function readEnumerators(collector: Collector, raw: unknown, at: string): EnumeratorSpec[] | null {
    const entries = collector.array(raw, at);
    if (entries === null) {
        return null;
    }
    const out: EnumeratorSpec[] = [];
    for (let i = 0; i < entries.length; i += 1) {
        const key = `${at}[${i}]`;
        const entry = collector.object(entries[i], key);
        if (entry === null) {
            continue;
        }
        const name = collector.string(entry, "name", `${key}.name`);
        const value = collector.integer(entry, "value", `${key}.value`);
        if (name === null || value === null) {
            continue;
        }
        out.push({ name, value });
    }
    return out;
}

