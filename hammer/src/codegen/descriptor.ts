type Raw = Readonly<Record<string, unknown>>;

function asObject(value: unknown): Raw | null {
    if (typeof value !== "object" || value === null || Array.isArray(value)) {
        return null;
    }
    return value as Raw;
}

class Collector {
    readonly errors: DescriptorProblem[] = [];
    readonly warnings: DescriptorProblem[] = [];

    error(key: string, issue: DescriptorIssue): void {
        this.errors.push({ key, issue });
    }

    warn(key: string, issue: DescriptorIssue): void {
        this.warnings.push({ key, issue });
    }

    object(value: unknown, key: string): Raw | null {
        const object = asObject(value);
        if (object === null) {
            this.error(key, "not-an-object");
        }
        return object;
    }

    array(value: unknown, key: string): readonly unknown[] | null {
        if (!Array.isArray(value)) {
            this.error(key, "not-an-array");
            return null;
        }
        return value;
    }

    string(holder: Raw, field: string, key: string): string | null {
        const value = holder[field];
        if (typeof value !== "string") {
            this.error(key, "not-a-string");
            return null;
        }
        return value;
    }

    integer(holder: Raw, field: string, key: string): number | null {
        const value = holder[field];
        if (typeof value !== "number" || !Number.isSafeInteger(value)) {
            this.error(key, "not-an-integer");
            return null;
        }
        return value;
    }

    boolean(holder: Raw, field: string, key: string): boolean | null {
        const value = holder[field];
        if (typeof value !== "boolean") {
            this.error(key, "not-a-boolean");
            return null;
        }
        return value;
    }

    strings(holder: Raw, field: string, key: string): string[] | null {
        const value = this.array(holder[field], key);
        if (value === null) {
            return null;
        }
        const out: string[] = [];
        for (let i = 0; i < value.length; i += 1) {
            const item = value[i];
            if (typeof item !== "string") {
                this.error(`${key}[${i}]`, "not-a-string");
                continue;
            }
            out.push(item);
        }
        return out;
    }

    member<T extends string>(
        holder: Raw,
        field: string,
        key: string,
        allowed: readonly T[],
    ): T | null {
        const value = holder[field];
        if (typeof value !== "string") {
            this.error(key, "not-a-string");
            return null;
        }
        const found = allowed.find((candidate) => candidate === value);
        if (found === undefined) {
            this.error(key, "unknown-member");
            return null;
        }
        return found;
    }

    // A name that is empty, or that cannot become an identifier without becoming
    // some other name's identifier. Both are reported against the name rather
    // than against the emission, because the emitter is not the thing that is
    // wrong.
    name(value: string, key: string): void {
        if (value.length === 0) {
            this.error(key, "empty");
            return;
        }
        if (!isSpellable(value)) {
            this.error(key, "not-spellable");
        }
    }
}

